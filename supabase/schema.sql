-- India Golf Carnival 2026-27 schema
create table if not exists public.cities (
  id smallint primary key,
  name text not null,
  sort_order smallint not null,
  start_date date not null,
  end_date date not null,
  status text not null default 'upcoming' check (status in ('upcoming','live','completed')),
  handicap_method text not null default 'tbc' check (handicap_method in ('super36','registered','tbc')),
  team text,
  venue text,
  is_final boolean not null default false
);

create table if not exists public.participants (
  id bigint generated by default as identity primary key,
  city_id smallint not null references public.cities(id),
  full_name text not null,
  gender text check (gender in ('M','F')),
  mobile text,
  email text,
  home_club text,
  handicap_index numeric(4,1),
  created_at timestamptz not null default now()
);
create index if not exists participants_city_idx on public.participants(city_id);

-- one score card per participant per city leg
create table if not exists public.scores (
  participant_id bigint primary key references public.participants(id) on delete cascade,
  city_id smallint not null references public.cities(id),
  gross smallint not null,
  pars smallint,
  birdies smallint,
  eagles smallint,
  handicap_applied smallint not null,   -- Super 36 day handicap, or course handicap from registered index
  net smallint not null,
  updated_at timestamptz not null default now()
);
create index if not exists scores_city_idx on public.scores(city_id);

-- Contains personal data: only signed-in staff can read. Writes via Supabase dashboard / service role.
alter table public.cities enable row level security;
alter table public.participants enable row level security;
alter table public.scores enable row level security;

create policy "staff read cities" on public.cities for select to authenticated using (true);
create policy "staff read participants" on public.participants for select to authenticated using (true);
create policy "staff read scores" on public.scores for select to authenticated using (true);

-- Staff allowlist: only emails listed here can read data (protects players' phone/email
-- even if someone signs themselves up through Supabase Auth).
create table if not exists public.staff (email text primary key, full_name text, added_at timestamptz not null default now());
alter table public.staff enable row level security;
create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.staff s where lower(s.email) = lower(auth.jwt() ->> 'email'));
$$;
create policy "staff read own row" on public.staff for select to authenticated using (lower(email) = lower(auth.jwt() ->> 'email'));
create policy "only staff cities" on public.cities as restrictive for select to authenticated using ((select public.is_staff()));
create policy "only staff participants" on public.participants as restrictive for select to authenticated using ((select public.is_staff()));
create policy "only staff scores" on public.scores as restrictive for select to authenticated using ((select public.is_staff()));

-- Registration opens city by city, just before each event
alter table public.cities add column if not exists registration_status text not null default 'not_open'
  check (registration_status in ('not_open','open','closed'));

-- Hole-by-hole scoring (18 holes)
create table if not exists public.holes (
  city_id smallint not null references public.cities(id),
  hole smallint not null check (hole between 1 and 18),
  par smallint not null check (par between 3 and 5),
  stroke_index smallint not null check (stroke_index between 1 and 18),
  primary key (city_id, hole)
);
create table if not exists public.hole_scores (
  participant_id bigint not null references public.participants(id) on delete cascade,
  hole smallint not null check (hole between 1 and 18),
  strokes smallint not null check (strokes between 1 and 15),
  primary key (participant_id, hole)
);
alter table public.holes enable row level security;
alter table public.hole_scores enable row level security;
create policy "staff read holes" on public.holes for select to authenticated using ((select public.is_staff()));
create policy "staff read hole_scores" on public.hole_scores for select to authenticated using ((select public.is_staff()));

